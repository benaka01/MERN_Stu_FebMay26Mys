// Comparison Operators
console.log("Comparison Operators");
let x=2,y="2";
console.log("x==y",x==y);//Loose Equality
console.log("x===y",x===y);//Strict Equality
console.log("x!=y",x!=y);//Loose Inequality
console.log("x!==y",x!==y);//Strict Inequality
console.log("x>3",x>3);//greater than 3
console.log("x<3",x<3);//Lesser than 3
console.log("x>=3",x>=3);//greater than or equals 3
console.log("x<=3",x<=3);//Lesser than or equals 3
